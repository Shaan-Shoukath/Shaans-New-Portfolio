/** Home page graph: profile page, roles, projects and events. */
export function homeJsonLd(content: PortfolioContent) {
  const roles = [...content.work, ...content.community].map((e) => ({
    "@type": "OrganizationRole",
    roleName: e.title,
    startDate: isoDate(e.start_date),
    ...(isCurrent(e) ? {} : { endDate: isoDate(e.end_date) }),
    description: e.description ?? undefined,
    [e.type === "social" ? "memberOf" : "worksFor"]: {
      "@type": "Organization",
      name: e.company,
    },
  }));

  const shipped = Object.entries(workProducts).flatMap(([company, list]) =>
    list
      .filter((p) => p.url)
      .map((p) => ({
        "@type": "SoftwareApplication",
        name: p.name,
        url: p.url,
        description: p.summary,
        image: productImages[p.name] ? absoluteUrl(productImages[p.name]) : undefined,
        applicationCategory: /play\.google/.test(p.url ?? "") ? "MobileApplication" : "WebApplication",
        producer: { "@type": "Organization", name: company },
        contributor: { "@id": PERSON_ID },
      }))
  );

  const projects = content.projects.map((p) => ({
    "@type": "SoftwareSourceCode",
    name: p.title,
    description: p.description ?? undefined,
    url: p.live_url ?? p.github_url ?? undefined,
    codeRepository: p.github_url ?? undefined,
    keywords: p.tech_stack.join(", "),
    image: (p.image_url ?? projectMeta[p.id]?.image) ? absoluteUrl((p.image_url ?? projectMeta[p.id]?.image)!) : undefined,
    creativeWorkStatus: projectMeta[p.id]?.role,
    author: { "@id": PERSON_ID },
  }));

  return {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "ProfilePage",
        "@id": `${siteConfig.url}/#profile`,
        url: siteConfig.url,
        name: siteConfig.title,
        description: siteConfig.description,
        inLanguage: "en-IN",
        isPartOf: { "@id": `${siteConfig.url}/#website` },
        mainEntity: { "@id": PERSON_ID },
        about: { "@id": PERSON_ID },
        dateModified: SITE_UPDATED,
      },
      { "@id": PERSON_ID, hasOccupation: roles.map((r) => ({ "@type": "Occupation", name: r.roleName })) },
      {
        "@type": "ItemList",
        name: "Projects by Shaan Shoukath",
        itemListElement: [...projects, ...shipped].map((item, i) => ({
          "@type": "ListItem",
          position: i + 1,
          item,
        })),
      },
      {
        "@type": "ItemList",
        name: "Roles held by Shaan Shoukath",
        itemListElement: roles.map((item, i) => ({ "@type": "ListItem", position: i + 1, item })),
      },
    ],
  };
}

export function breadcrumbJsonLd(items: Array<{ name: string; path: string }>) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: items.map((item, index) => ({
      "@type": "ListItem",
      position: index + 1,
      name: item.name,
      item: absoluteUrl(item.path),
    })),
  };
}
