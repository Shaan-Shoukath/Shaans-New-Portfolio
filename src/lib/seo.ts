/** Converts free-text dates ("May 2026", "2026") to ISO 8601 ("2026-05", "2026") for schema.org. */
export function isoDate(value: string | null | undefined): string | undefined {
  if (!value) return undefined;
  const t = value.trim();
  if (/^\d{4}(-\d{2}(-\d{2})?)?$/.test(t)) return t;
  const m = t.match(/^([A-Za-z]{3})[a-z]*\.?\s+(\d{4})$/);
  if (m) {
    const i = ["jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"].indexOf(m[1].toLowerCase());
    if (i >= 0) return `${m[2]}-${String(i + 1).padStart(2, "0")}`;
  }
  return undefined;
}

export function absoluteUrl(path = "/") {
  if (/^https?:\/\//i.test(path)) return path;
  return new URL(path, siteConfig.url).toString();
}

export function createPageMetadata({
  title,
  description,
  path = "/",
  type = "website",
  noIndex = false,
  keywords,
  image,
}: {
  title?: string;
  description: string;
  path?: string;
  type?: "website" | "article" | "profile";
  noIndex?: boolean;
  keywords?: string[];
  /** Overrides the generated share image (e.g. a blog cover). */
  image?: string;
}): Metadata {
  const canonical = absoluteUrl(path);
  const fullTitle = title ? `${title} | ${siteConfig.name}` : siteConfig.title;
  return {
    title: title ? title : { absolute: siteConfig.title },
    description,
    keywords: keywords?.length ? keywords : undefined,
    // Every page advertises the blog feed so readers and crawlers can find it.
    alternates: { canonical, types: { "application/rss+xml": absoluteUrl("/feed.xml") } },
    openGraph: {
      title: fullTitle,
      description,
      url: canonical,
      siteName: siteConfig.name,
      type,
      locale: "en_IN",
      // Page-level openGraph replaces the root one, so the share image must be set here.
      images: [
        image && image !== siteConfig.ogImage
          ? { url: absoluteUrl(image) }
          : { url: absoluteUrl(siteConfig.ogImage), width: 1200, height: 630, alt: siteConfig.title },
      ],
    },
    twitter: {
      card: "summary_large_image",
      title: fullTitle,
      description,
      images: [absoluteUrl(image && image !== siteConfig.ogImage ? image : siteConfig.ogImage)],
    },
    robots: noIndex ? { index: false, follow: false } : undefined,
  };
}

